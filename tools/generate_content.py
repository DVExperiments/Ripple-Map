SCENARIOS=[]

def add(id,title,icon,topic,question,intro,focus,nodes,links,incidents,loop,challenge):
    node_objs=[]
    for line in nodes.strip().splitlines():
        parts=[p.strip() for p in line.split('|')]
        assert len(parts)==4,(id,line)
        node_objs.append(dict(id=parts[0],title=parts[1],category=parts[2],description=parts[3]))
    link_objs=[]
    for line in links.strip().splitlines():
        p=[x.strip() for x in line.split('|')]
        assert len(p)==3,(id,line)
        a,b=p[0].split('>');link_objs.append(dict(source=a.strip(),target=b.strip(),kind=p[1],why=p[2]))
    obj=dict(id=id,title=title,icon=icon,topic=topic,question=question,intro=intro,focus=focus,nodes=node_objs,links=link_objs,incidents=[dict(node=x[0],title=x[1],description=x[2]) for x in incidents],loop=dict(nodes=loop[0],title=loop[1],insight=loop[2]),challenge=challenge)
    ids={x['id'] for x in node_objs};assert len(ids)==len(node_objs)
    assert 'core' in ids and next(x for x in node_objs if x['id']=='core')['category']=='core'
    assert all(e['source'] in ids and e['target'] in ids for e in link_objs)
    assert all(i['node'] in ids for i in obj['incidents'])
    assert all(x in ids for x in loop[0]);assert all(e['kind'] in {'requires','influences','affects'} for e in link_objs)
    SCENARIOS.append(obj)

